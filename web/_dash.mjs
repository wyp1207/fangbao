const b = await chromium.launch({ executablePath: process.env.HOME + '/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe' });
const c = await b.newContext({ viewport:{width:1600,height:1000} }); const p = await c.newPage();
const calls=[]; p.on('response', r=>{ if(r.url().includes('/api/')) calls.push(r.status()+' '+r.url().replace('http://127.0.0.1:5173','')); });
await p.goto('http://127.0.0.1:5173/login',{waitUntil:'networkidle'});
const i=await p.locator('input').all(); await i[0].fill('admin'); await i[1].fill('admin123');
await p.locator('button').filter({hasText:/登录|登 录/}).first().click().catch(()=>{});
await p.waitForTimeout(5000);
await p.goto('http://127.0.0.1:5173/dashboard',{waitUntil:'networkidle'}); await p.waitForTimeout(6000);
await p.screenshot({path:process.env.HOME+'/ptshots/dash-now.png'});
